/**
 * Embed server/database/news-seed/*.md into a TypeScript module so the
 * production Nitro image does not depend on process.cwd() or a copied
 * markdown directory. Runtime boot reads NEWS_SEED_EMBEDDED only.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const seedDir = join(root, 'server/database/news-seed')
const outFile = join(root, 'server/utils/newsSeedEmbedded.ts')

let files = []
try {
  files = readdirSync(seedDir)
    .filter(name => name.endsWith('.md') && name !== 'README.md')
    .sort()
}
catch {
  files = []
}

if (files.length === 0) {
  if (existsSync(outFile)) {
    console.log(`no news seed markdown in ${seedDir}; keeping existing ${outFile}`)
    process.exit(0)
  }
  throw new Error(`No news seed markdown files found in ${seedDir}`)
}

const catalog = Object.fromEntries(
  files.map(name => [name, readFileSync(join(seedDir, name), 'utf8')]),
)

const source = [
  '/* Generated by scripts/embed-news-seeds.mjs. Do not edit by hand. */',
  '',
  'export const NEWS_SEED_EMBEDDED: Readonly<Record<string, string>> = '
    + JSON.stringify(catalog, null, 2),
  '',
].join('\n')

writeFileSync(outFile, source)
console.log(`embedded ${files.length} news seed files into server/utils/newsSeedEmbedded.ts`)
